let CACHED_LEXICON_SET: Set<string> | null = null;

/**
 * Returns an O(1) Set containing all offline dictionary entries,
 * single-character words, idioms, and HSK lexical items.
 */
export function getCedictLexicon(): Set<string> {
  if (!CACHED_LEXICON_SET) {
    CACHED_LEXICON_SET = new Set<string>();

    // 1. Add core curated words & idioms
    for (const w of CORE_CHINESE_WORDS) {
      CACHED_LEXICON_SET.add(w);
    }

    // 2. Add offline lexicon entries
    for (const entry of OFFLINE_LEXICON) {
      if (entry.zh && entry.zh.trim()) {
        CACHED_LEXICON_SET.add(entry.zh.trim());
      }
    }

    // 3. Add single characters from single-character dictionary
    for (const char of Object.keys(SINGLE_CHAR_DICT)) {
      CACHED_LEXICON_SET.add(char);
    }

    // 4. Ensure all function/transition words exist in dictionary
    for (const fw of FUNCTION_WORDS) {
      CACHED_LEXICON_SET.add(fw);
    }
  }

  return CACHED_LEXICON_SET;
}
